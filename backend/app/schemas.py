class OrderCreate(BaseModel):
    items: list[OrderLineInput] = Field(min_length=1, max_length=40)
    payment_method: PaymentMethod
    address: str = Field(default="", max_length=500)
    latitude: float | None = Field(default=None, ge=-90, le=90)
    longitude: float | None = Field(default=None, ge=-180, le=180)
    notes: str = Field(default="", max_length=500)

    @model_validator(mode="after")
    def delivery_coordinates_are_paired(self):
        if (self.latitude is None) != (self.longitude is None):
            raise ValueError("Save both delivery coordinates together")
        return self
    scheduled_for: datetime | None = None

    @field_validator("scheduled_for", mode="before")
    @classmethod
    def parse_scheduled_for(cls, value):
        if not value or not isinstance(value, str):
            return value
        val = value.strip()
        if not val:
            return None
        if "T" not in val and ":" in val:
            from zoneinfo import ZoneInfo
            now_ist = datetime.now(ZoneInfo("Asia/Kolkata"))
            val = f"{now_ist.strftime('%Y-%m-%d')}T{val}"
        return val

    @field_validator("items")
    @classmethod
    def unique_items(cls, items: list[OrderLineInput]) -> list[OrderLineInput]:
        import json
        keys = []
        for item in items:
            raw_customs = [c.model_dump() if hasattr(c, "model_dump") else c for c in item.customizations]
            custom_key = json.dumps(raw_customs, sort_keys=True) if raw_customs else ""
            var_key = item.variation_name or ""
            keys.append((item.menu_item_id, item.custom_menu_item_id, var_key, custom_key))
        if len(keys) != len(set(keys)):
            raise ValueError("Each menu item selection can only appear once; adjust its quantity instead.")
        return items


